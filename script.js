function setupCanvas() {
  const canvas = document.getElementById("network-canvas");
  const ctx = canvas.getContext("2d");
  let points = [];

  function resize() {
    const ratio = Math.min(window.devicePixelRatio || 1, 2);
    canvas.width = window.innerWidth * ratio;
    canvas.height = window.innerHeight * ratio;
    canvas.style.width = `${window.innerWidth}px`;
    canvas.style.height = `${window.innerHeight}px`;
    ctx.setTransform(1, 0, 0, 1, 0, 0);
    ctx.scale(ratio, ratio);
    const count = Math.max(34, Math.floor(window.innerWidth / 34));
    points = Array.from({ length: count }, () => ({
      x: Math.random() * window.innerWidth,
      y: Math.random() * window.innerHeight,
      vx: (Math.random() - 0.5) * 0.24,
      vy: (Math.random() - 0.5) * 0.24
    }));
  }

  function step() {
    ctx.clearRect(0, 0, window.innerWidth, window.innerHeight);

    points.forEach((point) => {
      point.x += point.vx;
      point.y += point.vy;

      if (point.x < 0 || point.x > window.innerWidth) {
        point.vx *= -1;
      }

      if (point.y < 0 || point.y > window.innerHeight) {
        point.vy *= -1;
      }

      ctx.fillStyle = "rgba(77, 222, 255, 0.7)";
      ctx.beginPath();
      ctx.arc(point.x, point.y, 1.2, 0, Math.PI * 2);
      ctx.fill();
    });

    for (let i = 0; i < points.length; i += 1) {
      for (let j = i + 1; j < points.length; j += 1) {
        const dx = points[i].x - points[j].x;
        const dy = points[i].y - points[j].y;
        const distance = Math.sqrt((dx * dx) + (dy * dy));

        if (distance < 160) {
          ctx.strokeStyle = `rgba(68, 208, 255, ${0.18 * (1 - distance / 160)})`;
          ctx.lineWidth = 1;
          ctx.beginPath();
          ctx.moveTo(points[i].x, points[i].y);
          ctx.lineTo(points[j].x, points[j].y);
          ctx.stroke();
        }
      }
    }

    window.requestAnimationFrame(step);
  }

  resize();
  window.addEventListener("resize", resize);
  window.requestAnimationFrame(step);
}

function escapePdfText(text) {
  return text
    .replace(/\\/g, "\\\\")
    .replace(/\(/g, "\\(")
    .replace(/\)/g, "\\)")
    .replace(/[^\x20-\x7E]/g, " ");
}

function wrapText(text, size, maxWidth) {
  const measureCanvas = wrapText.canvas || (wrapText.canvas = document.createElement("canvas"));
  const ctx = measureCanvas.getContext("2d");
  ctx.font = `${size}px Arial`;

  const words = text.split(/\s+/);
  const lines = [];
  let current = "";

  words.forEach((word) => {
    const candidate = current ? `${current} ${word}` : word;
    if (ctx.measureText(candidate).width <= maxWidth || !current) {
      current = candidate;
    } else {
      lines.push(current);
      current = word;
    }
  });

  if (current) {
    lines.push(current);
  }

  return lines;
}

function buildResumePdf() {
  const basics = portfolioData.basics;
  const pageWidth = 595.28;
  const pageHeight = 841.89;
  const margin = 48;
  const contentWidth = pageWidth - (margin * 2);
  const pages = [[]];
  let y = pageHeight - margin;

  function currentPage() {
    return pages[pages.length - 1];
  }

  function addPage() {
    pages.push([]);
    y = pageHeight - margin;
  }

  function ensureSpace(required) {
    if (y - required < margin) {
      addPage();
    }
  }

  function push(command) {
    currentPage().push(command);
  }

  function addLine(x1, y1, x2, y2) {
    push("0.78 w");
    push("0.80 0.86 0.91 RG");
    push(`${x1.toFixed(2)} ${y1.toFixed(2)} m ${x2.toFixed(2)} ${y2.toFixed(2)} l S`);
  }

  function addText(text, x, font, size, color = "0 0 0", leading = size + 4) {
    push(`BT /${font} ${size} Tf ${color} rg 1 0 0 1 ${x.toFixed(2)} ${y.toFixed(2)} Tm (${escapePdfText(text)}) Tj ET`);
    y -= leading;
  }

  function addParagraph(text, size = 10.5, indent = 0, color = "0.24 0.28 0.32") {
    const lines = wrapText(text, size, contentWidth - indent);
    ensureSpace((size + 4) * lines.length + 8);
    lines.forEach((line) => addText(line, margin + indent, "F1", size, color, size + 4));
    y -= 4;
  }

  function addBulletList(items) {
    items.forEach((item) => {
      const lines = wrapText(`- ${item}`, 10, contentWidth - 18);
      ensureSpace((10 + 4) * lines.length + 2);
      lines.forEach((line, index) => {
        addText(line, margin + (index === 0 ? 0 : 14), "F1", 10, "0.24 0.28 0.32", 14);
      });
    });
    y -= 6;
  }

  function addSection(title) {
    ensureSpace(38);
    addText(title.toUpperCase(), margin, "F2", 12.5, "0.12 0.18 0.22", 16);
    addLine(margin, y + 4, pageWidth - margin, y + 4);
    y -= 12;
  }

  addText(basics.name, margin, "F2", 22, "0.08 0.12 0.16", 26);
  addText("Cybersecurity Analyst & IT Specialist", margin, "F1", 12, "0.24 0.28 0.32", 18);
  addText(
    `${basics.phone} | ${basics.email} | ${basics.location} | linkedin.com/in/surajvaikom | github.com/surajvaikom`,
    margin,
    "F1",
    9.5,
    "0.30 0.34 0.38",
    16
  );
  y -= 6;

  addSection("Professional Summary");
  addParagraph(
    "A certified Cybersecurity Analyst & IT Specialist with a passion for penetration testing, vulnerability assessment, and hardening digital defenses. Hands-on experience with Burp Suite, Nmap, Metasploit, Nessus, and Wireshark, combined with practical ERP, technical support, and security internship experience."
  );

  addSection("Core Skills");
  addParagraph("Cybersecurity: Penetration Testing, Vulnerability Assessment, Vulnerability Management, Incident Response, Network Security, SIEM, SOC Operations, OWASP Top 10.");
  addParagraph("IT & Technical Skills: ERP Management, Technical Support, Remote Troubleshooting, System Configuration, TCP/IP, DNS, DHCP, Python.");
  addParagraph("Professional & Compliance: Report Writing, Staff Training, Customer Service, Regulatory Compliance awareness, Operations Reporting, Digital Marketing.");

  addSection("Professional Experience");
  portfolioData.experience.forEach((job) => {
    ensureSpace(54);
    addText(job.title, margin, "F2", 11.5, "0.10 0.13 0.16", 15);
    addText(`${job.company} | ${job.date}`, margin, "F1", 10, "0.18 0.23 0.28", 15);
    addBulletList(job.details);
  });

  addSection("Education");
  portfolioData.education.forEach((item) => {
    ensureSpace(36);
    addText(item.degree, margin, "F2", 11, "0.10 0.13 0.16", 15);
    addText(`${item.school} | ${item.years}`, margin, "F1", 10, "0.24 0.28 0.32", 15);
    y -= 2;
  });

  addSection("Certifications");
  addBulletList(portfolioData.certifications.map((item) => `${item.title} - ${item.issuer}`));

  const objects = [null];
  const encoder = new TextEncoder();
  const allocate = () => {
    objects.push("");
    return objects.length - 1;
  };

  const fontRegular = allocate();
  const fontBold = allocate();
  const pagesRoot = allocate();
  const pageNumbers = [];
  const contentNumbers = [];

  pages.forEach((commands) => {
    const contentNumber = allocate();
    const pageNumber = allocate();
    contentNumbers.push(contentNumber);
    pageNumbers.push(pageNumber);

    const stream = commands.join("\n");
    objects[contentNumber] = `<< /Length ${encoder.encode(stream).length} >>\nstream\n${stream}\nendstream`;
  });

  objects[fontRegular] = "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>";
  objects[fontBold] = "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>";

  pageNumbers.forEach((pageNumber, index) => {
    objects[pageNumber] = `<< /Type /Page /Parent ${pagesRoot} 0 R /MediaBox [0 0 ${pageWidth} ${pageHeight}] /Resources << /Font << /F1 ${fontRegular} 0 R /F2 ${fontBold} 0 R >> >> /Contents ${contentNumbers[index]} 0 R >>`;
  });

  objects[pagesRoot] = `<< /Type /Pages /Count ${pageNumbers.length} /Kids [${pageNumbers.map((number) => `${number} 0 R`).join(" ")}] >>`;

  const catalog = allocate();
  objects[catalog] = `<< /Type /Catalog /Pages ${pagesRoot} 0 R >>`;

  let pdf = "%PDF-1.4\n";
  const offsets = [0];

  for (let index = 1; index < objects.length; index += 1) {
    offsets[index] = encoder.encode(pdf).length;
    pdf += `${index} 0 obj\n${objects[index]}\nendobj\n`;
  }

  const xrefStart = encoder.encode(pdf).length;
  pdf += `xref\n0 ${objects.length}\n`;
  pdf += "0000000000 65535 f \n";

  for (let index = 1; index < objects.length; index += 1) {
    pdf += `${String(offsets[index]).padStart(10, "0")} 00000 n \n`;
  }

  pdf += `trailer\n<< /Size ${objects.length} /Root ${catalog} 0 R >>\nstartxref\n${xrefStart}\n%%EOF`;
  return new Blob([pdf], { type: "application/pdf" });
}

function setupResumeDownload() {
  const button = document.getElementById("download-resume");
  button.addEventListener("click", () => {
    const blob = buildResumePdf();
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = "Suraj_N_S_ATS_Resume.pdf";
    link.click();
    window.setTimeout(() => URL.revokeObjectURL(url), 1000);
  });
}

